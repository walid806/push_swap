#include "push_swap.h"

int	sort_test(t_stack *a)
{
	if (!a || !(a)->next)
		return (0);
	while (a->next)
	{
		if (a->i < a->next->i)
			a = a->next;
		else
			return (1);
	}
	return (0);
}
